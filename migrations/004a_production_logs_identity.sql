begin;

-- production_logs.id -> GENERATED BY DEFAULT AS IDENTITY
-- BY DEFAULT (not ALWAYS): an explicitly supplied id still works, but an
-- omitted id is assigned from the sequence.
--
-- The ALTER is guarded so this file is safe to re-run (it was a bare ALTER when
-- first applied, and errored with "column ... already has a default" if repeated).
-- attidentity is '' when the column is NOT an identity column, 'd' for GENERATED
-- BY DEFAULT, 'a' for GENERATED ALWAYS — so only ALTER when ''.
do $$
begin
  if (select attidentity from pg_attribute
      where attrelid = 'public.production_logs'::regclass and attname = 'id') = '' then
    alter table public.production_logs alter column id add generated by default as identity;
  end if;
end $$;

select setval(
  pg_get_serial_sequence('public.production_logs', 'id'),
  coalesce((select max(id) from public.production_logs), 0) + 1,
  false
);

commit;

