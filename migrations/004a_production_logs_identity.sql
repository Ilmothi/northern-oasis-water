-- Same fix as migration 003, applied to production_logs: move id generation
-- into the database so the client never computes a colliding primary key.
--
-- production_logs is admin/manager only with no location filter, so it doesn't
-- hit the RLS-subset collision that affected sales. The risks here are:
--   * concurrent inserts from two devices/managers computing the same id, and
--   * a silently-rejected insert leaving inventory deducted/added (which
--     auto-persists) with no production record behind it — a BOM integrity gap.
-- The app code is updated in the same change to stop sending id, read the
-- DB-assigned id back via .select(), and apply inventory changes only on a
-- confirmed save.
--
-- No RLS policy changes. Apply via the Supabase SQL Editor AFTER review.
